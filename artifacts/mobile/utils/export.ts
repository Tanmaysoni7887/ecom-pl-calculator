import { Share, Platform } from "react-native";
import type { CalculationRecord, Store } from "@/context/DataContext";
import { formatCurrency, formatPercent, formatROAS, formatDate } from "./formatters";

export function buildCSV(calculations: CalculationRecord[], stores: Store[]): string {
  const storeMap = new Map(stores.map((s) => [s.id, s]));

  const headers = [
    "Date",
    "Product Name",
    "SKU",
    "Store",
    "Ad Platform",
    "Selling Price",
    "Product Cost",
    "Shipping Cost",
    "Packaging Cost",
    "Transaction Fee",
    "Payment Gateway Fee",
    "Taxes",
    "Discount %",
    "Refund Rate %",
    "Chargeback Rate %",
    "Ad Spend",
    "Orders",
    "Clicks",
    "Impressions",
    "Other Costs",
    "Revenue",
    "Adjusted Revenue",
    "Total COGS",
    "Total Variable Costs",
    "Gross Profit",
    "Net Profit",
    "Profit Margin %",
    "ROAS",
    "Breakeven ROAS",
    "CPA",
    "CPC",
    "CPM",
    "CTR %",
    "Conversion Rate %",
    "AOV",
    "Contribution Margin %",
    "Notes",
  ];

  const rows = calculations.map((c) => {
    const store = storeMap.get(c.storeId);
    const r = c.results;
    return [
      c.date,
      c.productName,
      c.sku,
      store?.name ?? "",
      c.adPlatform,
      c.sellingPrice,
      c.productCost,
      c.shippingCost,
      c.packagingCost,
      c.transactionFee,
      c.paymentGatewayFee,
      c.taxes,
      c.discount,
      c.refundRate,
      c.chargebackRate,
      c.adSpend,
      c.numberOfOrders,
      c.numberOfClicks,
      c.impressions,
      c.otherCosts,
      r.revenue.toFixed(2),
      r.adjustedRevenue.toFixed(2),
      r.totalCOGS.toFixed(2),
      r.totalVariableCosts.toFixed(2),
      r.grossProfit.toFixed(2),
      r.netProfit.toFixed(2),
      r.profitMargin.toFixed(2),
      r.roas.toFixed(2),
      r.breakevenROAS.toFixed(2),
      r.cpa.toFixed(2),
      r.cpc.toFixed(2),
      r.cpm.toFixed(2),
      r.ctr.toFixed(2),
      r.conversionRate.toFixed(2),
      r.aov.toFixed(2),
      r.contributionMargin.toFixed(2),
      c.notes.replace(/,/g, ";"),
    ]
      .map((v) => `"${v}"`)
      .join(",");
  });

  return [headers.join(","), ...rows].join("\n");
}

export function buildSummaryText(calc: CalculationRecord, storeName: string): string {
  const r = calc.results;
  return `
📊 P&L & ROAS Summary
━━━━━━━━━━━━━━━━━━━━━
Product: ${calc.productName}
Store: ${storeName}
Date: ${formatDate(calc.date)}
Ad Platform: ${calc.adPlatform}

💰 Revenue & Profit
Revenue: ${formatCurrency(r.revenue)}
Adj. Revenue: ${formatCurrency(r.adjustedRevenue)}
Net Profit: ${formatCurrency(r.netProfit)}
Profit Margin: ${formatPercent(r.profitMargin)}

📈 Ad Performance
ROAS: ${formatROAS(r.roas)}
Breakeven ROAS: ${formatROAS(r.breakevenROAS)}
CPA: ${formatCurrency(r.cpa)}
CPC: ${formatCurrency(r.cpc)}
CTR: ${formatPercent(r.ctr)}
Conversion Rate: ${formatPercent(r.conversionRate)}

📦 Costs
Total COGS: ${formatCurrency(r.totalCOGS)}
Total Variable Costs: ${formatCurrency(r.totalVariableCosts)}
Ad Spend: ${formatCurrency(calc.adSpend)}
AOV: ${formatCurrency(r.aov)}

Generated by Ecom P&L & ROAS Calculator
`.trim();
}

export async function shareCalculation(calc: CalculationRecord, storeName: string) {
  const text = buildSummaryText(calc, storeName);
  try {
    await Share.share({ message: text, title: `P&L: ${calc.productName}` });
  } catch {
    // user cancelled
  }
}

export async function exportCSV(calculations: CalculationRecord[], stores: Store[]) {
  const csv = buildCSV(calculations, stores);
  try {
    if (Platform.OS === "web") {
      // Web: download as file
      const blob = new Blob([csv], { type: "text/csv" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = "ecom_pl_history.csv";
      a.click();
      URL.revokeObjectURL(url);
    } else {
      await Share.share({
        message: csv,
        title: "Ecom P&L History Export",
      });
    }
  } catch {
    // user cancelled
  }
}
